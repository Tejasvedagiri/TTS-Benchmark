"""Reference voices: one clip + its exact transcript per speaker, for the cloning models.

Yours: `input/voices/<Speaker>.wav` + `<Speaker>.txt` (the transcript), matched to the speaker
name case-insensitively ("Old Man" -> old_man.wav also works). A few seconds to ~15 s of clean
speech works best. Any speaker without one gets a placeholder made with Kokoro-82M, a preset of
their gender from cast.json (the same preset the kokoro baseline uses), saying CLIP_TEXT.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from .direction import voice_slots
from .render import ROOT, run_runner

INPUT_VOICES = ROOT / "input" / "voices"
CLIP_TEXT = (
    "The quick brown fox jumps over the lazy dog while the autumn wind rustled golden leaves "
    "across the quiet street."
)


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_") or "voice"


def _rel(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def plan_voices(cast: dict, voices_dir: Path) -> dict[str, dict]:
    """{speaker: {clip, transcript, gender, slot, description, made}}; clip paths are relative
    to the repo root. `made`: a Kokoro placeholder (generated by make_missing_clips)."""
    yours = {slug(p.stem): p for p in INPUT_VOICES.glob("*.wav")} if INPUT_VOICES.exists() else {}
    slots = voice_slots(cast)
    out = {}
    for name, c in cast.items():
        clip = yours.get(slug(name))
        if clip is not None:
            txt = clip.with_suffix(".txt")
            if not txt.exists():
                raise SystemExit(f"{_rel(clip)} needs its exact transcript in {_rel(txt)}")
            transcript, made = txt.read_text(encoding="utf-8").strip(), False
        else:
            clip, transcript, made = voices_dir / f"{slug(name)}.wav", CLIP_TEXT, True
        out[name] = {
            "clip": _rel(clip),
            "transcript": transcript,
            "gender": c["gender"],
            "slot": slots[name],
            "description": c["description"],
            "made": made,
        }
    return out


def make_missing_clips(all_voices: dict[str, dict[str, dict]], output: Path, log) -> None:
    """Kokoro placeholders for every test's speakers that have no clip (one Kokoro load)."""
    rows = []
    for voices in all_voices.values():
        for name, v in voices.items():
            if v["made"] and not (ROOT / v["clip"]).exists():
                rel = (ROOT / v["clip"]).relative_to(output).with_suffix("")
                rows.append(
                    {
                        "id": rel.as_posix(),
                        "voice": name,
                        "text": CLIP_TEXT,
                        "voice_gender": v["gender"],
                        "voice_slot": v["slot"],
                    }
                )
    if not rows:
        return
    log(f"making {len(rows)} Kokoro reference clips")
    work = output / ".work" / "voices.jsonl"
    work.parent.mkdir(parents=True, exist_ok=True)
    work.write_text("".join(json.dumps(r) + "\n" for r in rows), encoding="utf-8")
    result = run_runner("kokoro", work, output, log)
    for row in rows:
        wav = output / f"{row['id']}.wav"
        if not wav.exists():
            why = result["errors"].get(row["id"]) or "; ".join(result["notes"]) or "unknown"
            raise SystemExit(f"could not make a reference clip for {row['voice']}: {why}")
        wav.with_suffix(".txt").write_text(CLIP_TEXT + "\n", encoding="utf-8")
